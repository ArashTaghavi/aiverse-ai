"""Extract compact table DDL for a CRUD context, without application rows."""

import json
import re
from copy import copy

from sqlalchemy import MetaData, inspect, select
from sqlalchemy.engine import Connection
from sqlalchemy.schema import CreateColumn, CreateIndex, CreateTable

from app.core.database import DbSession

from .models.database import Database
from .provisioning.database_connection_factory import DatabaseConnectionFactory
from .provisioning.types import DatabaseConnection

_QUOTED = r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|\[(?:\]\]|[^\]])*\]|`(?:``|[^`])*`"


def _column_nullability(specification: str, nullable: bool) -> str:
    depth = 0
    has_null = False

    def replace(match: re.Match[str]) -> str:
        nonlocal depth, has_null
        token = match.group(0)
        if token == "(":
            depth += 1
        elif token == ")":
            depth -= 1
        elif depth == 0 and token == "NOT NULL":
            return ""
        elif depth == 0 and token == "NULL":
            has_null = True
        return token

    result = re.sub(
        _QUOTED + r"|\bDEFAULT\s+NULL\b|[()]|\bNOT NULL\b|\bNULL\b",
        replace, specification,
    )
    return result + (" NULL" if nullable and not has_null else "")


def _column_specification(column, dialect) -> tuple[str, str]:
    original = str(CreateColumn(column).compile(dialect=dialect))
    specification = original
    if dialect.name == "postgresql" and column.server_default is not None:
        default = dialect.ddl_compiler(dialect, None).get_column_default_string(column)
        if default and re.match(r"^nextval\s*\(", default, re.IGNORECASE):
            specification = specification.replace("DEFAULT " + default, "AUTO", 1)

    aliases = {
        "AUTO_INCREMENT": "AUTO",
        "IDENTITY": "AUTO",
        "GENERATED ALWAYS AS IDENTITY": "AUTO ALWAYS",
        "GENERATED BY DEFAULT AS IDENTITY": "AUTO",
        "SERIAL": "INTEGER AUTO",
        "BIGSERIAL": "BIGINT AUTO",
        "SMALLSERIAL": "SMALLINT AUTO",
    }
    specification = re.sub(
        _QUOTED + r"|\b(?:GENERATED (?:ALWAYS|BY DEFAULT) AS IDENTITY"
        r"|AUTO_INCREMENT|IDENTITY|BIGSERIAL|SMALLSERIAL|SERIAL)\b",
        lambda match: aliases.get(match.group(0), match.group(0)),
        specification,
    )
    return original, _column_nullability(specification, column.nullable)


def _reflect_schema(connection: Connection) -> str:
    """Keep columns, types, nullability, generated values, keys and checks only."""
    inspector = inspect(connection)
    if connection.dialect.name in {"mysql", "mariadb"}:
        # In MySQL a schema is a database; inspect only the requested database.
        schemas = [connection.engine.url.database or inspector.default_schema_name]
    else:
        schemas = inspector.get_schema_names()
    schemas = sorted(
        schema for schema in schemas
        if schema not in {"information_schema", "INFORMATION_SCHEMA", "pg_catalog", "sys"}
        and not schema.startswith(("pg_toast", "pg_temp_"))
    )

    metadata = MetaData()
    for schema in schemas:
        metadata.reflect(bind=connection, schema=schema, views=False)

    # Omit schema qualifiers only when formatting the context, not during reflection.
    dialect = copy(connection.dialect)
    dialect.identifier_preparer = copy(connection.dialect.identifier_preparer)
    dialect.identifier_preparer.omit_schema = True

    statements = []
    for table in sorted(metadata.tables.values(), key=lambda item: item.key):
        # Strip names and comments only from the in-memory reflection.
        for constraint in table.constraints:
            constraint.name = None
        table.comment = None
        for vendor in ("mysql", "mariadb"):
            table.dialect_options.pop(vendor, None)
        for column in table.columns:
            column.comment = None
            if getattr(column.type, "collation", None) is not None:
                column.type = column.type.copy()
                column.type.collation = None

        ddl = str(CreateTable(
            table, include_foreign_key_constraints=list(table.foreign_key_constraints)
        ).compile(dialect=dialect))
        for column in table.columns:
            original, specification = _column_specification(column, dialect)
            ddl = ddl.replace(original, specification, 1)
        table_statements = [ddl.lstrip().removeprefix("CREATE TABLE ")]

        # Unique indexes impose write constraints, including filtered ones.
        # Ordinary indexes do not add logical schema information.
        unique_indexes = sorted(
            (index for index in table.indexes if index.unique),
            key=lambda index: index.name or "",
        )
        for index in unique_indexes:
            ddl = str(CreateIndex(index).compile(dialect=dialect))
            _, _, definition = ddl.partition(
                " ON " + dialect.identifier_preparer.format_table(table)
            )
            table_statements.append("UNIQUE" + definition)
        statements.append(" ".join(table_statements))

    # Preserve quoted values/identifiers; compact only formatting outside them.
    return "\n".join(re.sub(
        r"(?P<quoted>" + _QUOTED + r")"
        r"|(?P<keyword>\bPRIMARY KEY\b|\bFOREIGN KEY\b|\bIDENTITY\b)"
        r"|\s*(?P<punctuation>[(),])\s*|\s*;\s*|\s+",
        lambda match: match.group("quoted") or match.group("punctuation") or {
            "PRIMARY KEY": "PK", "FOREIGN KEY": "FK", "IDENTITY": "AUTO",
        }.get(match.group("keyword"), " "),
        statement,
    ).strip() for statement in statements)


async def extract_database_schema(
    db: DbSession,
    database_id: int,
    owner_id: int,
) -> str:
    """Read the owner's saved connection and return plain-text table DDL."""
    database = db.scalar(select(Database).where(
        Database.id == database_id, Database.owner_id == owner_id,
    ))
    if database is None:
        raise ValueError("Database not found")

    stored = database.connection
    credentials = json.loads(stored) if isinstance(stored, str) else stored
    return await extract_schema_from_connection(credentials)


async def extract_schema_from_connection(credentials: DatabaseConnection) -> str:
    """Return plain-text DDL, with each table and its unique indexes on one line."""
    connection_args = {key: credentials[key] for key in (
        "database_type", "host", "port", "database", "username", "password",
    )}
    engine = DatabaseConnectionFactory.create(**connection_args)
    try:
        async with engine.connect() as connection:
            return await connection.run_sync(_reflect_schema)
    finally:
        await engine.dispose()
